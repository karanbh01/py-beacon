# src/beacon/synthetic/dividends.py
"""
When each generated name goes ex-dividend and is paid.

Every name pays quarterly. In a store generated by py-beacon 0.9.7 or later
each name has its own timing, kept for its whole life: which of the three
quarterly cycles it pays in (January, April, July and October; February, May,
August and November; or March, June, September and December), the day of the
month it goes ex on, and how many days later the cash arrives. So the
dividends of a large universe land across the year, as a real market's do.

A store generated earlier put every name on the first session on or after the
15th of February, May, August and November, paid 21 days later. An extension
of such a store keeps that, so its history and its new days agree.
"""
# BN-357: with every name going ex on the same day, effects that turn on
# dividend timing landed together: a 6,000-name backtest's tracking error was
# inflated by the ex-date and pay-date gaps of 1,155 names on the same days.
import zlib

import numpy as np
import pandas as pd

# How a store's dividends are timed: the name is recorded in its generator
# state, so an extension times its new dividends the same way.
FIXED = "fixed"
SPREAD = "spread"

# FIXED's timing: the first session on or after the 15th of February, May,
# August and November, deliberately off the quarter starts where index
# rebalances land, and paid 21 days later.
FIXED_CYCLE = 1
FIXED_DAY = 15
FIXED_SETTLEMENT_DAYS = 21

# SPREAD's ranges. The day stops at the 28th so every month has it; the
# settlement covers the two to five weeks real dividends take to be paid.
LAST_DAY = 28
SETTLEMENT_DAYS = (14, 35)

# The months of each cycle.
CYCLES = ((1, 4, 7, 10), (2, 5, 8, 11), (3, 6, 9, 12))

# Mixed into a name's seed so its timing is a stream of its own, apart from
# every draw that shapes its prices.
_STREAM = 0xD1D


def timings(identifiers: pd.Index,
            seed: int,
            schedule: str = FIXED) -> pd.DataFrame:
    """Each name's dividend cycle, day of the month and settlement days.

    Under SPREAD a name's timing comes from the store's seed and its own
    identifier, so it is the same whenever and alongside whatever it is
    generated, and an extension can work it out again.

    Args:
        identifiers: The names.
        seed: The store's seed.
        schedule: FIXED or SPREAD.

    Returns:
        pd.DataFrame: ``cycle`` (0 to 2), ``day`` and ``settlement`` (days),
        one row per name.
    """
    if schedule == FIXED:
        rows = [(FIXED_CYCLE, FIXED_DAY, FIXED_SETTLEMENT_DAYS)] * len(identifiers)
    elif schedule == SPREAD:
        rows = [_spread(str(name), seed) for name in identifiers]
    else:
        raise ValueError(f"Unknown dividend schedule: {schedule!r}.")

    return pd.DataFrame(rows, index=identifiers, columns=["cycle", "day", "settlement"])


def _spread(identifier: str,
            seed: int) -> tuple[int, int, int]:
    """One name's timing under SPREAD."""
    rng = np.random.default_rng([seed, _STREAM, zlib.crc32(identifier.encode("utf-8"))])
    low, high = SETTLEMENT_DAYS

    return (int(rng.integers(len(CYCLES))), int(rng.integers(1, LAST_DAY + 1)),
            int(rng.integers(low, high + 1)))


def ex_dates(calendar: pd.DatetimeIndex,
             cycle: int,
             day: int) -> pd.DatetimeIndex:
    """The ex-dates in *calendar* for one timing: in each month of the
    cycle, the first session on or after *day*, or the month's last session
    when none is.

    The last session stands in only for a month *calendar* covers to its
    end: in the month the calendar stops in, the day may simply not have
    come yet.
    """
    months = CYCLES[cycle]
    on_or_after: dict[tuple[int, int], pd.Timestamp] = {}
    last: dict[tuple[int, int], pd.Timestamp] = {}

    for date in calendar:
        if date.month not in months:
            continue

        month = (date.year, date.month)
        last[month] = date

        if date.day >= day:
            on_or_after.setdefault(month, date)

    unfinished = (calendar[-1].year, calendar[-1].month) if len(calendar) else None
    chosen = [on_or_after.get(month, final)
              for month, final in last.items()
              if month in on_or_after or month != unfinished]

    return pd.DatetimeIndex(sorted(chosen))


def fractions(universe: pd.DataFrame,
              dates: pd.DatetimeIndex,
              calendar: pd.DatetimeIndex,
              timing: pd.DataFrame) -> pd.DataFrame:
    """The ex-date price drop, as a fraction of price, per name and date.

    A quarter of each name's dividend yield on each of its ex-dates in
    *dates*. The ex-dates come from *calendar*, which an extension reaches
    back before its first date, so a month the store already paid in is not
    given a second ex-date.
    """
    drops = np.zeros((len(dates), len(universe)))
    quarterly = universe["dividend_yield"].to_numpy() / 4.0
    rows = timing.loc[universe.index]

    # One search per timing rather than per name: there are at most 84.
    for (cycle, day), group in rows.groupby(["cycle", "day"]).groups.items():
        days = ex_dates(calendar, int(cycle), int(day)).intersection(dates)

        if days.empty:
            continue

        columns = universe.index.get_indexer(group)
        at = dates.get_indexer(days)
        drops[np.ix_(at, columns)] = quarterly[columns]

    return pd.DataFrame(drops, index=dates, columns=universe.index)
