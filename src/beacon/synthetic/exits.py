# src/beacon/synthetic/exits.py
"""
How a generated name leaves the market: taken over, or failed.

In a store generated by py-beacon 0.9.7 or later, a name's chance of leaving
falls with its size, as well as with its strength, and each exit is one of
two kinds:

- **A takeover**, likelier the larger the company: announced some weeks
  ahead, when the price jumps to the offer, a premium over the last close,
  less a small spread for the risk the deal fails; the price then closes the
  spread and the last close is the offer, which the holders are paid. Bids
  are fewer when markets are in turmoil.
- **A failure**: no warning and no premium, likelier in a crisis, and
  concentrated in smaller names.

How many names leave is unchanged: the same rate, only who and how.

A store generated earlier has every exit a failure, whatever the name's
size, and an extension of it keeps that.
"""
# BN-360: on a 600-name store, seven of the 109 names over 1bn that TTIX held
# delisted in the first quarter of 2020, most of them into the March crash.
import zlib

import numpy as np
import pandas as pd

# How a store's exits are drawn: recorded in its generator state, so an
# extension draws its own the same way.
UNIFORM = "uniform"
SIZED = "sized"

FAILURE = "failure"
TAKEOVER = "takeover"

# How much likelier a small company is to leave than a large one: each
# name's propensity goes with its market cap to this power, against the
# universe's typical size.
SIZE_SENSITIVITY = 0.5

# The share of exits that are takeovers, from the smallest company to the
# largest.
TAKEOVER_SHARE = (0.3, 0.9)

# Sessions between a bid's announcement and the last day of trading, the
# premium the offer carries over the last close, and the spread the price
# keeps below it until the deal closes.
ANNOUNCEMENT_SESSIONS = (40, 120)
PREMIUM = (0.20, 0.45)
SPREAD = (0.01, 0.04)

# Mixed into a name's seed, so its exit is a stream of its own, apart from
# every other draw.
_STREAM = 0xE217


def smallness(market_cap: np.ndarray) -> np.ndarray:
    """Each name's relative propensity to leave by its size: above one for a
    small company, below for a large one, with a mean of one."""
    caps = np.asarray(market_cap, dtype=float)
    typical = np.exp(np.mean(np.log(caps)))
    weight = (caps / typical) ** -SIZE_SENSITIVITY

    return np.asarray(weight / weight.mean())


def classify(lives: pd.DataFrame,
             market_cap: np.ndarray,
             inner: pd.DatetimeIndex,
             takeover_hazard: np.ndarray,
             seed: int) -> pd.DataFrame:
    """Each leaving name's kind of exit, and for a takeover its timing and terms.

    A takeover's last day is drawn again from *takeover_hazard*, since bids
    are timed by calm markets rather than by crises; one that would end before
    the name lists, or leave no room for its announcement, stays a failure.

    Args:
        lives: ``listed_from`` and ``listed_to`` per name, indexed by
            identifier.
        market_cap: Each name's market cap, in the order of *lives*.
        inner: The sessions an exit may fall on.
        takeover_hazard: The per-session hazard of a bid, over *inner*.
        seed: The store's seed.

    Returns:
        pd.DataFrame: *lives* with ``listed_to`` moved for each takeover, and
        ``exit``, ``announced``, ``premium`` and ``spread``.
    """
    frame = lives.copy()
    frame["exit"] = frame["listed_to"].notna().map({True: FAILURE, False: None})
    frame["announced"] = pd.NaT
    frame["premium"] = np.nan
    frame["spread"] = np.nan

    ranks = pd.Series(market_cap, index=frame.index).rank(pct=True)
    low, high = TAKEOVER_SHARE
    weights = takeover_hazard / takeover_hazard.sum()

    for name in frame.index[frame["listed_to"].notna()]:
        rng = np.random.default_rng([seed, _STREAM, zlib.crc32(str(name).encode("utf-8"))])
        share = low + (high - low) * ranks[name]

        if rng.uniform() >= share:
            continue

        last = int(rng.choice(len(inner), p=weights))
        lead = int(rng.integers(ANNOUNCEMENT_SESSIONS[0], ANNOUNCEMENT_SESSIONS[1] + 1))
        first = last - lead

        if first < 1 or inner[first] <= frame.at[name, "listed_from"]:
            continue

        frame.at[name, "exit"] = TAKEOVER
        frame.at[name, "listed_to"] = inner[last]
        frame.at[name, "announced"] = inner[first]
        frame.at[name, "premium"] = rng.uniform(*PREMIUM)
        frame.at[name, "spread"] = rng.uniform(*SPREAD)

    return frame


def apply(universe: pd.DataFrame,
          returns: pd.DataFrame) -> pd.DataFrame:
    """The returns with each takeover written in: the jump to the offer, less
    its spread, on the day it is announced, then a steady close of the spread
    to the last day, which ends at the offer.

    A name without an announced takeover, or whose deal falls outside the
    panel, keeps the returns it has.
    """
    if "exit" not in universe:
        return returns

    adjusted = returns.copy()
    dates = pd.DatetimeIndex(adjusted.index)
    deals = universe.loc[universe["exit"].eq(TAKEOVER) & universe.index.isin(adjusted.columns)]

    for name, deal in deals.iterrows():
        window = dates[(dates >= deal["announced"]) & (dates <= deal["listed_to"])]

        if len(window) < 2:
            continue

        offer = 1.0 + float(deal["premium"])
        kept = 1.0 - float(deal["spread"])
        adjusted.loc[window[0], name] = offer * kept - 1.0
        adjusted.loc[window[1:], name] = (1.0 / kept) ** (1.0 / (len(window) - 1)) - 1.0

    return adjusted
